// Command quan-build builds a quan into its own program: the quanar's host, which holds main,
// linked with the quan's package. The quan's code has no main of its own.
//
//	go tool quan-build                    build once into dist/<name>
//	go tool quan-build --watch            rebuild on every change, serve the program and announce each build on /events
//
// The port is the quan's, from its conf.qu; --port overrides it.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"io/fs"
	"log"
	"net/http"
	"os"
	"os/exec"
	"path"
	"path/filepath"
	"strconv"
	"strings"
	"sync"
	"time"

	"github.com/fsnotify/fsnotify"
)

const hostPackage = "shop-quanar/host"

// The quan's program: the host's main, with the quan's Mount.
const mainTemplate = `// Generated by quan-build. The quan has no main; this is the quanar's host.
package main

import (
	"%s"

	quan %q
)

func main() { host.Run(quan.Manifest) }
`

func goOutput(args ...string) (string, error) {
	out, err := exec.Command("go", args...).Output()
	return strings.TrimSpace(string(out)), err
}

func build(module, name, out string) error {
	if err := os.MkdirAll(".quan", 0o755); err != nil {
		return err
	}
	source := fmt.Sprintf(mainTemplate, hostPackage, module)
	if err := os.WriteFile(filepath.Join(".quan", "main.go"), []byte(source), 0o644); err != nil {
		return err
	}
	// Static and reproducible: the same source makes the same program, and the same hash.
	cmd := exec.Command("go", "build", "-trimpath", "-ldflags=-s -w -buildid=", "-o", out+".tmp", "./.quan")
	cmd.Env = append(os.Environ(), "CGO_ENABLED=0")
	var stderr bytes.Buffer
	cmd.Stderr = &stderr
	if err := cmd.Run(); err != nil {
		return fmt.Errorf("%v\n%s", err, stderr.String())
	}
	if err := os.MkdirAll(filepath.Dir(out), 0o755); err != nil {
		return err
	}
	if err := os.Rename(out+".tmp", out); err != nil {
		return err
	}
	info, _ := os.Stat(out)
	log.Printf("built %s (%.1f MB)", out, float64(info.Size())/(1<<20))
	return nil
}

// announcer keeps the open /events streams.
type announcer struct {
	mu      sync.Mutex
	streams map[chan struct{}]bool
}

func (a *announcer) announce() {
	a.mu.Lock()
	defer a.mu.Unlock()
	for s := range a.streams {
		select {
		case s <- struct{}{}:
		default:
		}
	}
}

func (a *announcer) serve(w http.ResponseWriter, r *http.Request) {
	w.Header().Set("Content-Type", "text/event-stream")
	w.Header().Set("Cache-Control", "no-cache")
	flusher, _ := w.(http.Flusher)
	// Sent at once, so the quanar knows the quan is here.
	fmt.Fprint(w, ": connected\n\n")
	flusher.Flush()
	s := make(chan struct{}, 1)
	a.mu.Lock()
	a.streams[s] = true
	a.mu.Unlock()
	defer func() {
		a.mu.Lock()
		delete(a.streams, s)
		a.mu.Unlock()
	}()
	for {
		select {
		case <-s:
			fmt.Fprint(w, "event: change\ndata: {}\n\n")
			flusher.Flush()
		case <-r.Context().Done():
			return
		}
	}
}

func watch(module, name, out string, port int, serving bool) error {
	a := &announcer{streams: map[chan struct{}]bool{}}
	if serving {
		go serve(a, name, out, port)
	}
	watcher, err := fsnotify.NewWatcher()
	if err != nil {
		return err
	}
	defer watcher.Close()
	err = filepath.WalkDir(".", func(p string, d fs.DirEntry, err error) error {
		if err != nil || !d.IsDir() {
			return err
		}
		if p != "." && (strings.HasPrefix(d.Name(), ".") || d.Name() == "dist") {
			return filepath.SkipDir
		}
		return watcher.Add(p)
	})
	if err != nil {
		return err
	}
	// Blocks until the source changes; a burst of writes is one build.
	var settle <-chan time.Time
	for {
		select {
		case event := <-watcher.Events:
			if strings.HasSuffix(event.Name, ".go") || path.Base(event.Name) == "go.mod" {
				settle = time.After(100 * time.Millisecond)
			}
		case <-settle:
			if err := build(module, name, out); err != nil {
				log.Print(err)
				continue
			}
			a.announce()
		case err := <-watcher.Errors:
			return err
		}
	}
}

// serve serves the program and announces each new build on /events.
func serve(a *announcer, name, out string, port int) {
	mux := http.NewServeMux()
	mux.HandleFunc("GET /events", a.serve)
	mux.HandleFunc("GET /"+name, func(w http.ResponseWriter, r *http.Request) {
		w.Header().Set("Cache-Control", "no-store")
		http.ServeFile(w, r, out)
	})
	log.Printf("%s served at http://localhost:%d/%s, new builds announced at /events", name, port, name)
	log.Fatal(http.ListenAndServe(fmt.Sprintf(":%d", port), mux))
}

// confPort reads the quan's port from its conf.qu, or falls back to 4001.
func confPort() int {
	b, err := os.ReadFile("conf.qu")
	if err != nil {
		return 4001
	}
	for _, line := range strings.Split(string(b), "\n") {
		if fields := strings.Fields(line); len(fields) == 2 && fields[0] == "port" {
			if n, err := strconv.Atoi(fields[1]); err == nil {
				return n
			}
		}
	}
	return 4001
}

func main() {
	log.SetFlags(0)
	watching := flag.Bool("watch", false, "rebuild on every change and serve the program")
	port := flag.Int("port", 0, "where --watch serves the program and /events; the quan's conf.qu port by default")
	output := flag.String("out", "", "where to write the program; dist/<name> by default")
	serving := flag.Bool("serve", true, "with --watch, serve the program and /events; off when something else serves it")
	flag.Parse()

	module, err := goOutput("list", "-f", "{{.ImportPath}}", ".")
	if err != nil {
		log.Fatal("run quan-build in a quan's folder: ", err)
	}
	name := path.Base(module)
	out := *output
	if out == "" {
		out = filepath.Join("dist", name)
	}
	if err := build(module, name, out); err != nil {
		log.Fatal(err)
	}
	if *watching {
		if *port == 0 {
			*port = confPort()
		}
		log.Fatal(watch(module, name, out, *port, *serving))
	}
}
